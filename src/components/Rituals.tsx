import { useState } from "react";
import { holyDays, prayerParts } from "../data/scripture";
import SectionTitle from "./SectionTitle";

const pick = <T,>(a: T[]) => a[Math.floor(Math.random() * a.length)];

const makePrayer = () => ({
  o: pick(prayerParts.openings),
  m: pick(prayerParts.middles),
  c: pick(prayerParts.closings),
});

export default function Rituals() {
  const [prayer, setPrayer] = useState(makePrayer);
  const [n, setN] = useState(0);

  return (
    <section id="rituals" className="relative overflow-hidden py-28">
      <div className="absolute inset-0 bg-gradient-to-b from-ink via-[#1a0a10] to-ink" />
      <div className="relative mx-auto max-w-7xl px-5">
        <SectionTitle
          kicker="Liturgy & Observance"
          title="Sacred Rituals"
          subtitle="The holy calendar of the faithful, and a prayer for every occasion, freshly generated by the Faahlord."
        />

        <div className="grid gap-8 lg:grid-cols-2">
          {/* Calendar */}
          <div className="rounded-3xl border border-gold/25 bg-ink/70 p-6 md:p-8">
            <h3 className="font-deco text-2xl text-gold">📅 The Holy Calendar</h3>
            <ul className="mt-6 divide-y divide-gold/10">
              {holyDays.map((d) => (
                <li key={d.name} className="flex gap-5 py-4">
                  <span className="w-28 shrink-0 rounded-lg border border-gold/30 bg-gold/5 py-2 text-center font-cinzel text-sm font-semibold text-gold">
                    {d.date}
                  </span>
                  <div>
                    <p className="font-cinzel font-semibold text-parchment">{d.name}</p>
                    <p className="text-parchment/60 italic">{d.desc}</p>
                  </div>
                </li>
              ))}
            </ul>
          </div>

          {/* Prayer generator */}
          <div className="flex flex-col rounded-3xl border border-gold/25 bg-gradient-to-br from-velvet/80 to-ink p-6 md:p-8">
            <h3 className="font-deco text-2xl text-gold">🙏 The Prayer Generator</h3>
            <p className="mt-2 text-parchment/60 italic">For when thou knowest not what to pray. Which is always.</p>

            <div key={n} className="page-in parchment relative mt-6 flex flex-1 flex-col justify-center rounded-2xl p-8 text-center">
              <span className="absolute top-3 left-4 font-deco text-5xl text-red-900/20">"</span>
              <p className="text-xl leading-relaxed md:text-2xl">
                {prayer.o}
                <br />
                <em>{prayer.m}</em>
                <br />
                {prayer.c}
              </p>
            </div>

            <div className="mt-6 flex flex-wrap gap-3">
              <button
                onClick={() => {
                  setPrayer(makePrayer());
                  setN((x) => x + 1);
                }}
                className="flex-1 rounded-full bg-gold px-6 py-3 font-cinzel text-sm font-bold tracking-widest text-ink uppercase transition hover:scale-[1.02]"
              >
                ✨ New Prayer
              </button>
              <button
                onClick={() => {
                  const u = new SpeechSynthesisUtterance(`${prayer.o} ${prayer.m} ${prayer.c}`);
                  u.rate = 0.85;
                  u.pitch = 0.6;
                  window.speechSynthesis?.cancel();
                  window.speechSynthesis?.speak(u);
                }}
                className="flex-1 rounded-full border border-gold/50 px-6 py-3 font-cinzel text-sm tracking-widest text-gold uppercase transition hover:bg-gold/10"
              >
                🔊 Recite Aloud
              </button>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}
